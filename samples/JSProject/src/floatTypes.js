function calculatePi() {
    let pi = 3.14159;  // Float literal - will mutate to 3, 3.14159e0
    return pi;
}

function halfValue(x) {
    let half = 0.5;  // Float literal
    return x * half;
}

function precisionTest() {
    let precise = 0.1;  // Classic floating point
    return precise + 0.2;
}

function negativeFloat() {
    let negative = -2.5;  // Negative float
    return negative;
}

function smallDecimal() {
    let small = 0.001;  // Small decimal
    return small;
}


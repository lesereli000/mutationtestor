function largeNumber() {
    let large = 1e10;  // Exponential - will mutate to 10000000000, 10000000000.0
    return large;
}

function smallNumber() {
    let small = 1e-5;  // Small exponential (0.00001)
    return small;
}

function scientificCalculation(x) {
    let coefficient = 2.5e3;  // 2500
    return x * coefficient;
}

function negativeExponent() {
    let value = 5e-3;  // 0.005
    return value;
}

function largeExponent() {
    let huge = 1e20;  // Very large number
    return huge;
}
